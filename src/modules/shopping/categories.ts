const norm = (s: string) => s.trim().toLowerCase().replace(/["׳'״]/g, '')

const INDEX = Object.entries(KEYWORDS)
  .flatMap(([cat, words]) => words.map(w => ({ cat, w: norm(w) })))
  .sort((a, b) => b.w.length - a.w.length) // longest (most specific) match wins

/** Best-guess department for a product name, learning from products already categorized elsewhere */
export function guessCategory(name: string, known: Pick<ShoppingItem, 'name' | 'category'>[] = []): string {
  const n = norm(name)
  const learned = known.find(k => norm(k.name) === n)
  if (learned) return learned.category
  const words = n.split(/\s+/)
  const hit = INDEX.find(({ w }) => (w.includes(' ') ? n.includes(w) : words.some(x => x.startsWith(w))))
  return hit?.cat ?? 'אחר'
}

export const sameName = (a: string, b: string) => norm(a) === norm(b)
export const matches = (name: string, query: string) => norm(name).includes(norm(query))
export const categoryRank = (c: string) => { const i = (CATEGORIES as readonly string[]).indexOf(c); return i < 0 ? 999 : i }
